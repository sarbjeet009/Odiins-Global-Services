            <p><strong>Role:</strong> Visiting kirana stores, supermarkets, and B2B dealers across Khurda, Cuttack, and Puri districts to book daily wholesale orders.</p>
            <p><strong>Crucial Skillset:</strong> Valid two-wheeler license, market route familiarity, and strong local merchant relationships.</p>
            <p><strong>Salary Benchmark in Bhubaneswar:</strong> ₹13,000 – ₹22,000/month + travel allowance and daily incentives.</p>
