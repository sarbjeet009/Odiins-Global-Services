          <h2>2. Why DIY Hiring Leads to 50%+ Showroom Attrition</h2>
          <p>
            Many store owners place a "Walk-in Interview" poster on their showroom glass or post in unmoderated local groups. This DIY approach creates three massive operational vulnerabilities:
          </p>
          <ol class="styled-list">
            <li><strong>Unvetted Walk-ins without Reference Audits:</strong> Anyone off the street walks into your cash area. Without Aadhaar background audits and previous employer cross-checks, cash discrepancies and theft risks multiply.</li>
            <li><strong>Chronic Punctuality Issues:</strong> When an employee commutes 25 km from outside the city, morning opening punctuality falls apart. Showrooms opening at 10:00 AM cannot tolerate staff arriving at 10:45 AM.</li>
            <li><strong>Festive Desertion:</strong> Unregulated staff routinely walk out right before peak seasonal sales events when other retailers offer temporary ₹500 extra per day.</li>
          </ol>

