          <h2>1. What is a Bank CSP (Customer Service Point)?</h2>
          <p>
            A Bank CSP (also known as a Business Correspondent or Bank Mitra) acts as a mini-branch of a major commercial bank—such as State Bank of India (SBI), Bank of India (BOI), Punjab National Bank (PNB), or Odisha Gramya Bank (OGB).
          </p>
          <p>
            Instead of villagers traveling 10 to 15 kilometers to a crowded block-level bank branch, they visit their local village CSP kiosk to perform essential financial transactions:
          </p>
          <div class="info-card">
            <h4>Core Services Offered at an Odisha Bank CSP:</h4>
            <ul>
              <li><strong>Instant Savings Account Opening:</strong> Jan Dhan / Regular Savings accounts opened in minutes via biometric e-KYC.</li>
              <li><strong>AePS Cash Withdrawals &amp; Deposits:</strong> Aadhaar-enabled Biometric Micro-ATM transactions for all banks.</li>
              <li><strong>Direct Benefit Transfer (DBT) Payouts:</strong> Subhadra Yojana, PM-KISAN, Kalia Yojana, and elderly pension disbursements.</li>
              <li><strong>Domestic Money Remittances:</strong> Instant IMPS/NEFT transfers to any bank account across India.</li>
              <li><strong>Micro-Insurance &amp; Pension:</strong> Enrolling villagers in PMJJBY, PMSBY, and Atal Pension Yojana (APY).</li>
              <li><strong>Loan Referrals &amp; Passbook Printing:</strong> Facilitating Mudra loans, KCC loans, and printing transaction statements.</li>
            </ul>
