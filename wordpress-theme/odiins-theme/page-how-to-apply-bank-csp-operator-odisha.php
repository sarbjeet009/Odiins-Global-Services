          <h2>2. Eligibility Criteria for Applicants in Odisha</h2>
          <p>
            To be approved by partner financial institutions, applicants must meet these baseline credentials:
          </p>
          <ul>
            <li><strong>Age:</strong> Minimum 18 years and above.</li>
            <li><strong>Education:</strong> Minimum 10th or 12th pass from a recognized board (BSE Odisha / CBSE). Basic computer literacy is mandatory.</li>
            <li><strong>Mandatory Certification:</strong> IIBF (Indian Institute of Banking &amp; Finance) BC/BF Certification. (Candidates in the process of clearing IIBF can initiate application matching through Odiins).</li>
            <li><strong>Clean Background Check:</strong> Valid Police Verification Certificate (PVC) from the local district police station with zero criminal record.</li>
            <li><strong>Credit History:</strong> Satisfactory personal CIBIL score (free of willful bank loan defaults).</li>
          </ul>

          <hr class="section-divider">

          <h2>3. Shop &amp; Infrastructure Requirements</h2>
          <p>
            You do not need an expensive commercial complex to operate a Bank CSP kiosk. A compact, clean counter space satisfies operational compliance:
          </p>
          <ol class="styled-list">
            <li><strong>Space:</strong> 80 to 150 sq. ft. commercial or semi-commercial room (owned or rented with formal lease agreement).</li>
            <li><strong>Location:</strong> Situated at least 3 to 5 km away from the nearest physical base branch of the designated bank, preferably near a village chowk, market center, or bus stand.</li>
            <li><strong>Hardware Equipment Required:</strong>
              <ul>
                <li>Laptop or Desktop PC with Windows 10/11 operating system.</li>
                <li>Morpho or Mantra Biometric Fingerprint Scanner (RD Service compliant).</li>
                <li>All-in-One Printer, Scanner &amp; Copier.</li>
                <li>Stable Internet Connectivity (Fiber Broadband or 4G/5G mobile hotspot).</li>
                <li>Power Inverter / UPS backup (minimum 2 hours battery life for rural areas).</li>
              </ul>
            </li>
          </ol>

